def _image(name, path):
    img = bpy.data.images.get(name)
    if img is None and path and os.path.exists(path):
        img = bpy.data.images.load(path, check_existing=True)
        img.name = name
    return img


def _materials(me, mats):
    for m in mats:
        if m is None:
            me.materials.append(None)
            continue
        mt = bpy.data.materials.get(m['name'])
        if mt is None:
            mt = bpy.data.materials.new(m['name'])
            mt.use_nodes = True
            img = _image(m['image'], m['image_path']) if m['image'] else None
            if img is not None:
                nt = mt.node_tree
                tex = nt.nodes.new('ShaderNodeTexImage')
                tex.image = img
                nt.nodes.active = tex  # (Workbench's textured views draw the active image node)
                bsdf = nt.nodes.get('Principled BSDF')
                if bsdf:
                    nt.links.new(tex.outputs['Color'], bsdf.inputs['Base Color'])
        me.materials.append(mt)


def build_mesh(d, points=None, faces=None):
    me = bpy.data.meshes.new(d.get('mesh', d['name']))
    pts = points if points is not None else d['points']
    fs = faces if faces is not None else d['faces']
    me.from_pydata(pts, [], fs)
    me.validate(clean_customdata=False)
    if len(me.polygons) != len(fs) or len(me.vertices) != len(pts):
        raise RuntimeError('%s: mesh changed on build (%d/%d faces)' % (d['name'], len(me.polygons), len(fs)))
    if 'sharp_face' not in d.get('attributes', {}):  # (no sharp_face: every face smooth; a new mesh starts flat)
        me.shade_smooth()
    for name, per_face in d.get('uv_layers', {}).items():
        layer = me.uv_layers.new(name=name)
        for p, uvs in zip(me.polygons, per_face):
            for li, uv in zip(p.loop_indices, uvs):
                layer.data[li].uv = uv
    if d.get('uv_active'):
        me.uv_layers.active = me.uv_layers[d['uv_active']]
    edge_index = {tuple(sorted(e.vertices)): e.index for e in me.edges}
    for name, a in d.get('attributes', {}).items():
        at = me.attributes.get(name) or me.attributes.new(name, a['type'], a['domain'])
        field = {'FLOAT_VECTOR': 'vector', 'FLOAT_COLOR': 'color', 'FLOAT2': 'vector'}.get(a['type'], 'value')
        vals = a['values']
        if a['domain'] == 'EDGE':
            for item in vals:
                i = edge_index[tuple(sorted(item[:2]))]
                setattr(at.data[i], field, True if a['type'] == 'BOOLEAN' else item[2])
        elif a['domain'] == 'CORNER':
            for p, vs in zip(me.polygons, vals):
                for li, v in zip(p.loop_indices, vs):
                    setattr(at.data[li], field, v)
        else:
            for x, v in zip(at.data, vals):
                setattr(x, field, v)
    _materials(me, d.get('materials', []))
    ob = bpy.data.objects.new(d['name'], me)
    bpy.context.scene.collection.objects.link(ob)
    for g in d.get('vertex_groups', []):
        ob.vertex_groups.new(name=g)
    for vi, ws in enumerate(d.get('weights', [])):
        for gi, w in ws:
            ob.vertex_groups[gi].add([vi], w, 'REPLACE')
    return ob


def build_weapon(d):
    import numpy as np
    path, raw, tris = weapon_raw(d['name'], d['props'])
    if raw is None:
        raise RuntimeError('%s: the game model %s was not found' % (d['name'], path))
    A = np.array(d['msh_to_local'])
    pts = [list(A @ np.array([*r, 1.0])) for r in raw]
    return build_mesh(d, pts, [list(t) for t in tris])


def build_armature(d):
    arm = bpy.data.armatures.new(d.get('armature', d['name']))
    arm.display_type = d.get('display_type', 'OCTAHEDRAL')
    ob = bpy.data.objects.new(d['name'], arm)
    bpy.context.scene.collection.objects.link(ob)
    bpy.context.view_layer.objects.active = ob
    bpy.ops.object.mode_set(mode='EDIT')
    ebs = {}
    for b in d['bones']:
        eb = arm.edit_bones.new(b['name'])
        eb.head = (0, 0, 0)
        eb.tail = (0, b['length'], 0)
        eb.matrix = Matrix(b['matrix_local'])
        eb.length = b['length']
        eb.use_deform = b['use_deform']
        eb.use_inherit_rotation = b['use_inherit_rotation']
        eb.inherit_scale = b['inherit_scale']
        eb.use_local_location = b['use_local_location']
        ebs[b['name']] = eb
    for b in d['bones']:
        if b['parent']:
            ebs[b['name']].parent = ebs[b['parent']]
            ebs[b['name']].use_connect = b['use_connect']
    bpy.ops.object.mode_set(mode='OBJECT')
    for b in d['bones']:
        for k, v in b.get('props', {}).items():
            arm.bones[b['name']][k] = v
    for name, p in d.get('pose', {}).items():
        pb = ob.pose.bones[name]
        pb.rotation_mode = p['rotation_mode']
        pb.matrix_basis = Matrix(p['matrix_basis'])
        for k, v in p.get('props', {}).items():
            pb[k] = v
    return ob


def place(ob, d):
    """Parent, parent bone, matrices, properties and the armature modifier, once every object exists."""
    for k, v in d.get('props', {}).items():
        ob[k] = v
    if d.get('parent'):
        ob.parent = bpy.data.objects[d['parent']]
        ob.parent_type = d['parent_type']
        if d['parent_type'] == 'BONE':
            ob.parent_bone = d['parent_bone']
    ob.matrix_parent_inverse = Matrix(d['matrix_parent_inverse'])
    ob.matrix_basis = Matrix(d['matrix_basis'])
    for m in d.get('modifiers', []):
        mod = ob.modifiers.new(m['name'], m['type'])
        if m.get('object'):
            mod.object = bpy.data.objects[m['object']]
