"""Our models as text (idren2023 2026-11-04: every model we made rebuildable from git plus the installed game).

Used inside Blender by tools/body_save.py (a blend -> tools/data/models/<set>/*.json) and tools/body_rebuild.py (those
files + the game's own files -> a blend). What goes into text: our meshes (points, faces, uvs, every attribute such as
sharp edges and creases, vertex groups and weights, materials by name and image), our skeletons (bones' rest frames,
parents, flags, the current pose), every object's place (parent, parent bone, matrices) and custom properties. What
does not: the game's own models and textures. A weapon placed in the hand is saved as its msh file and the affine map
from that msh's coordinates to the object's own (rebuilt by reading the msh from the mod tools' assets); an image is
saved by its file path (a game texture read from the game's folders, one of ours regenerated by tools/body_textures.sh).
"""
import json
import os
import sys

import bpy
from mathutils import Matrix

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mshgeo  # noqa: E402

MSH_DIR = 'C:/LucasArts/BFBuilder/Assets/Sides/ALL/MSH'
CANISTER_MSH = 'C:/LucasArts/BFBuilder/Assets/Shipped Add On/DataTAT3/Common/MSHs/item_powerup_ammo.msh'
SKIP_ATTRIBUTES = {'position', 'distort'}  # (position: saved as points; distort: tools/body_sbd.py's heat map)


def num(x):
    return float('%.9g' % x)  # a float32 written so that it reads back the same


def mat(m):
    return [[num(m[r][c]) for c in range(len(m[r]))] for r in range(len(m))]


def plain(v):
    """An ID property as plain json values (arrays, groups and lists of them, nested)."""
    if hasattr(v, 'to_list'):
        return v.to_list()
    if hasattr(v, 'to_dict'):
        return {k: plain(x) for k, x in v.to_dict().items()}
    if isinstance(v, (list, tuple)):
        return [plain(x) for x in v]
    return v


def props_of(idb):
    out = {}
    for k in idb.keys():
        v = plain(idb[k])
        try:
            json.dumps(v)
        except TypeError:
            continue
        out[k] = v
    return out


def placement(ob):
    return {'name': ob.name, 'type': ob.type, 'parent': ob.parent.name if ob.parent else None,
            'parent_type': ob.parent_type, 'parent_bone': ob.parent_bone,
            'matrix_parent_inverse': mat(ob.matrix_parent_inverse), 'matrix_basis': mat(ob.matrix_basis),
            'props': props_of(ob),
            'modifiers': [{'type': m.type, 'name': m.name, 'object': getattr(m, 'object', None) and m.object.name}
                          for m in ob.modifiers if m.type == 'ARMATURE']}


def image_path(img):
    return bpy.path.abspath(img.filepath, library=img.library).replace('\\', '/') if img.filepath else None


def materials_of(me):
    out = []
    for m in me.materials:
        if m is None:
            out.append(None)
            continue
        imgs = [n.image for n in m.node_tree.nodes if n.type == 'TEX_IMAGE' and n.image] if m.use_nodes else []
        out.append({'name': m.name, 'image': imgs[0].name if imgs else None,
                    'image_path': image_path(imgs[0]) if imgs else None})
    return out


def save_mesh(ob):
    me = ob.data
    d = placement(ob)
    d['mesh'] = me.name
    d['points'] = [[num(c) for c in v.co] for v in me.vertices]
    d['faces'] = [list(p.vertices) for p in me.polygons]
    d['uv_layers'] = {}
    for layer in me.uv_layers:
        d['uv_layers'][layer.name] = [[[num(layer.data[li].uv.x), num(layer.data[li].uv.y)] for li in p.loop_indices]
                                      for p in me.polygons]
    d['uv_active'] = me.uv_layers.active.name if me.uv_layers.active else None
    edges = [tuple(e.vertices) for e in me.edges]
    attrs = {}
    for a in me.attributes:
        if a.name.startswith('.') or a.name in SKIP_ATTRIBUTES or a.name in me.uv_layers:
            continue
        if a.data_type not in ('FLOAT', 'INT', 'BOOLEAN', 'INT8', 'FLOAT_VECTOR', 'FLOAT_COLOR', 'FLOAT2'):
            continue
        field = {'FLOAT_VECTOR': 'vector', 'FLOAT_COLOR': 'color', 'FLOAT2': 'vector'}.get(a.data_type, 'value')
        vals = []
        for x in a.data:
            v = getattr(x, field)
            vals.append([num(c) for c in v] if field != 'value' else (num(v) if a.data_type == 'FLOAT' else
                                                                       (int(v) if a.data_type != 'BOOLEAN' else bool(v))))
        if a.domain == 'CORNER':  # by face and corner, as the uvs
            vals = [[vals[li] for li in p.loop_indices] for p in me.polygons]
        if a.domain == 'EDGE':  # by the edge's two points
            if a.data_type == 'BOOLEAN':
                vals = [list(edges[i]) for i, v in enumerate(vals) if v]
            else:
                vals = [[*edges[i], v] for i, v in enumerate(vals) if v]
        attrs[a.name] = {'domain': a.domain, 'type': a.data_type, 'values': vals}
    d['attributes'] = attrs
    d['vertex_groups'] = [g.name for g in ob.vertex_groups]
    d['weights'] = [[[g.group, num(g.weight)] for g in v.groups] for v in me.vertices]
    d['materials'] = materials_of(me)
    return d


def weapon_raw(name, props):
    """The msh a weap_ object was built from and its points in the order tools/body_weapons.py and
    tools/body_export.py take them (the drawn, textured segments; the canister: every drawn segment)."""
    is_canister = name == 'weap_ammocanister'
    short = props.get('grip', name[5:])
    if 'msh' in props:
        path = props['msh']
    elif is_canister:
        path = CANISTER_MSH
    elif len(short) > 4 and short[3] == '_':
        side = {'all': 'ALL', 'wok': 'ALL', 'imp': 'IMP', 'rep': 'REP', 'cis': 'CIS'}[short[:3]]
        path = os.path.join(MSH_DIR.replace('/ALL/', '/%s/' % side), '%s_1st_weap_inf_%s.msh' % (short[:3], short[4:]))
    else:
        path = os.path.join(MSH_DIR, 'all_1st_weap_inf_%s.msh' % short)
    if not os.path.exists(path):
        return path, None, None
    model = mshgeo.load(path)
    raw, tris = [], []
    for node in model['nodes']:
        if not mshgeo.is_drawn(node) or 'lens' in node['name'].lower():
            continue
        for seg in node['segments']:
            if not is_canister and (not seg.get('uv') or not seg.get('texture') or seg['texture'].endswith('.pic')):
                continue
            base = len(raw)
            raw += [tuple(p) for p in seg['wpos']]
            tris += [(base + a, base + b, base + c) for a, b, c in seg.get('tris', [])]
    return path, raw, tris


def save_weapon(ob):
    """A weapon from the game placed in the hand: its msh and the map msh -> the object's own coordinates (fitted
    over its points); one that is not the msh's points (a placement of ours: tools/body_sbd.py's direct grip) as a mesh."""
    import numpy as np
    path, raw, _ = weapon_raw(ob.name, props_of(ob))
    co = [v.co for v in ob.data.vertices]
    if raw is not None and len(raw) == len(co) and not ob.get('direct'):
        X = np.array([[*r, 1.0] for r in raw])
        Y = np.array([list(c) for c in co])
        A = np.linalg.lstsq(X, Y, rcond=None)[0]
        err = float(np.abs(X @ A - Y).max())
        if err < 1e-5:
            d = placement(ob)
            d['weapon_msh'] = path
            d['msh_to_local'] = [[num(A[c, r]) for c in range(4)] for r in range(3)]
            d['fit_error_m'] = err
            d['materials'] = materials_of(ob.data)
            return d
    return save_mesh(ob)


def save_armature(ob):
    d = placement(ob)
    arm = ob.data
    d['armature'] = arm.name
    d['display_type'] = arm.display_type
    d['bones'] = [{'name': b.name, 'parent': b.parent.name if b.parent else None,
                   'matrix_local': mat(b.matrix_local), 'length': num(b.length),
                   'head_local': [num(c) for c in b.head_local], 'tail_local': [num(c) for c in b.tail_local],
                   'use_connect': b.use_connect, 'use_deform': b.use_deform,
                   'use_inherit_rotation': b.use_inherit_rotation, 'inherit_scale': b.inherit_scale,
                   'use_local_location': b.use_local_location, 'props': props_of(b)} for b in arm.bones]
    d['pose'] = {pb.name: {'rotation_mode': pb.rotation_mode, 'matrix_basis': mat(pb.matrix_basis),
                           'props': props_of(pb)} for pb in ob.pose.bones}
    return d


def write(d, path):
    """One object per file; one point, face or weight list per line (readable diffs)."""
    lines = ['{']
    keys = list(d)
    for i, k in enumerate(keys):
        v = d[k]
        end = ',' if i < len(keys) - 1 else ''
        if isinstance(v, list) and v and isinstance(v[0], (list, dict)) and k != 'matrix_basis' and not k.startswith('matrix'):
            lines.append('  %s: [' % json.dumps(k))
            lines += ['    %s%s' % (json.dumps(x, separators=(',', ':')), ',' if j < len(v) - 1 else '')
                      for j, x in enumerate(v)]
            lines.append('  ]' + end)
        else:
            lines.append('  %s: %s%s' % (json.dumps(k), json.dumps(v, separators=(',', ':')), end))
    lines.append('}')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')


