"""python tools/lvllabels_inc.py [out.inc]: tools/lvllabels.json (tools/lvlmatch.py: which .msh node each triangle of
the game's munged models came from) as a C++ include for src/StockTables.cpp. Our own data (names and counts): the
build makes it from git, no game files needed."""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else 'build/gen/LvlLabels.inc'
    labels = json.load(open(os.path.join(HERE, 'lvllabels.json')))
    os.makedirs(os.path.dirname(out) or '.', exist_ok=True)
    with open(out, 'w') as f:
        f.write('// Generated by tools/lvllabels_inc.py from tools/lvllabels.json: do not edit.\n')
        names = []
        for index, (msh, entry) in enumerate(sorted(labels.items())):
            f.write('constexpr LabelRun LABEL_RUNS_%d[] = {\n' % index)
            for segment, runs in enumerate(entry['segments']):
                for node, count in runs:
                    f.write('    {%d, "%s", %d},\n' % (segment, node, count))
            f.write('};\n')
            names.append((msh, entry, index))
        f.write('constexpr ModelLabels MODEL_LABELS[] = {\n')
        for msh, entry, index in names:
            shift = entry['shift']
            f.write('    {"%s", "%s", "%s", {%r, %r, %r}, LABEL_RUNS_%d, %d},\n' % (
                msh, entry['lvl'], entry['model'], shift[0], shift[1], shift[2], index,
                sum(len(r) for r in entry['segments'])))
        f.write('};\n')


if __name__ == '__main__':
    main()
