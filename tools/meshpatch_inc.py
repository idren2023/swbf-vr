"""python tools/meshpatch_inc.py [out.inc]: tools/data/meshpatch (tools/meshpatch.py: our game-derived meshes as
places on the player's game models plus offsets) as a C++ include for src/GameMeshes.cpp. The build runs it; our data
only, no game files needed."""
import json
import os
import struct
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, 'data', 'meshpatch')


def num(x):
    s = '%.9g' % x  # a float32 written so that it reads back the same
    return (s if ('.' in s or 'e' in s or 'n' in s) else s + '.') + 'f'


def lines(values, per_line, fmt):
    return '\n'.join('    ' + ','.join(fmt(v) for v in values[i:i + per_line]) + ','
                     for i in range(0, len(values), per_line))


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else 'build/gen/MeshPatches.inc'
    meta = json.load(open(os.path.join(DATA, 'meshpatch.json')))
    os.makedirs(os.path.dirname(out) or '.', exist_ok=True)
    entries = []
    with open(out, 'w') as f:
        f.write('// Generated by tools/meshpatch_inc.py from tools/data/meshpatch: do not edit.\n')
        for index, name in enumerate(sorted(meta)):
            m = meta[name]
            raw = zlib.decompress(open(os.path.join(DATA, name + '.z'), 'rb').read())
            count = struct.unpack_from('<I', raw)[0]
            tris = struct.unpack_from('<%di' % count, raw, 4)
            values = struct.unpack_from('<%df' % (10 * count), raw, 4 + 4 * count)
            f.write('constexpr int MESH_TRIANGLES_%d[] = {\n%s\n};\n' % (index, lines(tris, 24, str)))
            f.write('constexpr float MESH_VALUES_%d[] = {\n%s\n};\n' % (index, lines(values, 10, num)))
            entries.append('{"%s", "%s", "%s", 0x%08xu, %d, {%s}, %d, MESH_TRIANGLES_%d, MESH_VALUES_%d}' % (
                name, m['lvl'], m['model'], m['hash'], m['flip_v'], ', '.join(num(v) for v in m['transform']), count,
                index, index))
        f.write('constexpr MeshPatch MESH_PATCHES[] = {\n    %s,\n};\n' % ',\n    '.join(entries))
    print('meshpatch_inc: %d tables -> %s' % (len(entries), out))


if __name__ == '__main__':
    main()
