"""python tools/texpatch_inc.py [out.inc]: tools/data/texpatch (tools/texpatch.py: our arm and body textures as
recipes on the player's game textures plus differences) as a C++ include for src/GameTextures.cpp. The build runs it;
our data only, no game files needed."""
import json
import os
import struct
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, 'data', 'texpatch')
OPS = {'copy': 0, 'luma': 1, 'fill': 2, 'remap': 3}


def words(values, per_line=12, fmt='0x%08x'):
    out = []
    for i in range(0, len(values), per_line):
        out.append('    ' + ','.join(fmt % v for v in values[i:i + per_line]) + ',')
    return '\n'.join(out)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else 'build/gen/TexturePatches.inc'
    meta = json.load(open(os.path.join(DATA, 'texpatch.json')))
    # tables built from other tables come after them
    order = []
    while len(order) < len(meta):
        for name in sorted(meta):
            if name in order:
                continue
            needs = [r['source'] for r in meta[name]['recipe'] if isinstance(r['source'], str)]
            if all(n in order for n in needs):
                order.append(name)
    os.makedirs(os.path.dirname(out) or '.', exist_ok=True)
    with open(out, 'w') as f:
        f.write('// Generated by tools/texpatch_inc.py from tools/data/texpatch: do not edit.\n')
        for index, name in enumerate(order):
            entry = meta[name]
            regions = []
            for k, r in enumerate(entry['recipe']):
                map_name = 'nullptr'
                if r['op'] == 'remap':
                    raw = zlib.decompress(open(os.path.join(DATA, r['map']), 'rb').read())
                    shorts = [v for (v,) in struct.iter_unpack('<h', raw)]
                    map_name = 'PATCH_MAP_%d_%d' % (index, k)
                    f.write('constexpr short %s[] = {\n%s\n};\n' % (map_name, words(shorts, 24, '%d')))
                source = r['source']
                if source is None:
                    kind, lvl, tex, table, h = 0, '', '', '', 0
                elif isinstance(source, str):
                    kind, lvl, tex, table, h = 2, '', '', source, 0
                else:
                    h = next(s['fnv1a'] for s in entry['sources'] if s['texture'] == source[1])
                    kind, lvl, tex, table = 1, source[0], source[1], ''
                params = (r.get('params') or []) + [0] * 6
                frm = r.get('from', [0, 0, 0, 0])
                regions.append('{%d, "%s", "%s", "%s", 0x%08xu, {%d, %d, %d, %d}, {%d, %d, %d, %d}, %d, {%s}, %s}' % (
                    kind, lvl, tex, table, h, *frm, *r['to'], OPS[r['op']], ', '.join(str(p) for p in params[:6]),
                    map_name))
            f.write('constexpr PatchRegion PATCH_REGIONS_%d[] = {\n    %s,\n};\n' % (index, ',\n    '.join(regions)))
            delta_name = 'nullptr'
            if not entry['unchanged']:
                raw = zlib.decompress(open(os.path.join(DATA, name + '.z'), 'rb').read())
                values = [v for (v,) in struct.iter_unpack('<I', raw)]
                delta_name = 'PATCH_DELTA_%d' % index
                f.write('constexpr unsigned %s[] = {\n%s\n};\n' % (delta_name, words(values)))
        f.write('constexpr TexturePatch TEXTURE_PATCHES[] = {\n')
        for index, name in enumerate(order):
            entry = meta[name]
            f.write('    {"%s", %d, %d, PATCH_REGIONS_%d, %d, %s},\n' % (
                name, entry['width'], entry['height'], index, len(entry['recipe']),
                'nullptr' if entry['unchanged'] else 'PATCH_DELTA_%d' % index))
        f.write('};\n')


if __name__ == '__main__':
    main()
