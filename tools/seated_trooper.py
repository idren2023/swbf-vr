"""python tools/seated_trooper.py [out.inc] [--obj out.obj]: the seated clone trooper (tools/body_seated_trooper.py's
re/body/seated/seated.json, Blender space: facing -y, z up) as a C++ table of StockVertex for src/ShellDesigns.cpp
(SEATED_TROOPER, texture 3: the design's exteriorName slot carries rep_inf_trooper), in shell space (x right, y up,
z back, facing -z) about the seat point: the middle of the seat under his hips. Without the JSON the table is empty
(the troop bay is then built without troopers). Generated from the game's model: not in git."""
import json, math, os, sys

SRC = 're/body/seated/seated.json'


def main():
    args = sys.argv[1:]
    obj = None
    if '--obj' in args:
        i = args.index('--obj')
        obj = args[i + 1]
        del args[i:i + 2]
    out = args[0] if args else 'build/gen/SeatedTrooper.inc'
    os.makedirs(os.path.dirname(out) or '.', exist_ok=True)
    tris = json.load(open(SRC))['tris'] if os.path.exists(SRC) else []
    # the seat point: under the hips (the lowest point of the body behind the knees, above the knees' height - 0.2)
    seat = [p for t in tris for p in t['p'] if p[1] > -0.12 and p[2] > 0.85]
    sz = min(p[2] for p in seat) if seat else 0
    sy = sum(p[1] for p in seat) / len(seat) if seat else 0
    rows = []
    for t in tris:
        ps = [(-p[0], p[2] - sz, p[1] - sy) for p in t['p']]  # Blender -> shell: right = -x, up = z, back = y
        e1 = [ps[1][k] - ps[0][k] for k in range(3)]
        e2 = [ps[2][k] - ps[0][k] for k in range(3)]
        n = (e1[1] * e2[2] - e1[2] * e2[1], e1[2] * e2[0] - e1[0] * e2[2], e1[0] * e2[1] - e1[1] * e2[0])
        length = math.sqrt(sum(c * c for c in n)) or 1
        n = tuple(c / length for c in n)
        rows.append((ps, n, [(uv[0], 1 - uv[1]) for uv in t['uv']]))
    with open(out, 'w') as f:
        f.write('// Generated by tools/seated_trooper.py from the game\'s clone trooper: not in git, do not edit.\n')
        f.write('constexpr int SEATED_TROOPER_COUNT = %d;\n' % (3 * len(rows)))
        f.write('constexpr StockVertex SEATED_TROOPER[%d] = {\n' % max(3 * len(rows), 1))
        for ps, n, uvs in rows:
            for p, uv in zip(ps, uvs):
                f.write('    {{%.4ff, %.4ff, %.4ff}, {%.4ff, %.4ff, %.4ff}, %.5ff, %.5ff, 3},\n' % (*p, *n, *uv))
        if not rows:
            f.write('    {{0, 0, 0}, {0, 1, 0}, 0, 0, 3},\n')
        f.write('};\n')
    if obj:
        with open(obj, 'w') as o:
            o.write('usemtl rep_inf_trooper\n')
            for i, (ps, n, uvs) in enumerate(rows):
                for p, uv in zip(ps, uvs):
                    o.write('v %.4f %.4f %.4f\nvt %.5f %.5f\n' % (*p, uv[0], 1 - uv[1]))
                o.write('f %d/%d %d/%d %d/%d\n' % (3 * i + 1, 3 * i + 1, 3 * i + 2, 3 * i + 2, 3 * i + 3, 3 * i + 3))
    print('seated trooper: %d triangles, seat at Blender z %.3f' % (len(rows), sz))


main()
