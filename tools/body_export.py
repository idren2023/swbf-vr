"""Blender (blender -b --factory-startup re/body/r_arm_weapons.blend -P tools/body_export.py -- <out.inc>): writes our
first-person right arm for the DLL as a C++ include (generated, never in git: it is shaped on the game's models; the
build copies re/body/BodyArm.inc into build/gen when it exists, as tools/mirrorstock.py's output):

- parts: r_hand_retopo (the glove: all_1st_inf_trooper_hands), r_forearm_retopo and r_forearm_stud (the sleeve and
  cuff's stud: all_1st_inf_trooper_arms), each as triangles over vertices split where uvs differ; per vertex position,
  normal, uv and up to four bones with weights (the largest four, summing to 1).
- bones: the rig's bones in an order where every parent comes first: name, parent, rest matrix (4x4, column vectors,
  bone space -> arm space), Euler order of its pose angles (the finger knuckles ZXY: swing then curl; the others XYZ),
  and the twist bones' share of the hand's roll (forearm_twist 0.5, wrist_twist 1.0).
- poses: every pose of tools/body_poses.py (label, then bone and Euler angles in degrees, in the bone's own frame).
- grips: per weapon (weap_*: tools/body_weapons.py, placed by tools/body_placeweapon.py; the thermal at the stock's
  place) the matrix from its msh model space (the game's own drawing of it) to the hand bone's rest frame, fitted
  over its vertices; it carries our scale (0.712 of the stock first-person model's, as the hand) and the msh -> arm
  axes, so drawing the weapon with it fits the grip.

Skeletons (PLAN 60 step 4): the human rig (r_hand_retopo's parent) first, then every armature with a `skeleton`
property (its name: "b1"), sorted by it, all in one bone table (BODY_ARM_SKELETONS: each one's range). A part, or a
weap_ grip, belongs to the skeleton of the armature it is parented to (a grip without a parent: the human one); a pose
group named "<skeleton> <group>" in tools/body_poses.py poses that skeleton's bones. The human rows come out as before.

Arm space is Blender's hand frame: metres, the wrist at the origin, +y toward the middle knuckle, +z the back of the
hand, right-handed (the DLL converts to the game's axes). Prints counts and checks (weights, indices)."""
import bpy, json, glob, math, os, sys
from mathutils import Vector

args = sys.argv[sys.argv.index('--') + 1:]
OUT = args[0]
MSH_DIR = 'C:/LucasArts/BFBuilder/Assets/Sides/ALL/MSH'
CANISTER_MSH = 'C:/LucasArts/BFBuilder/Assets/Shipped Add On/DataTAT3/Common/MSHs/item_powerup_ammo.msh'
PARTS = (('r_hand_retopo', 'all_1st_inf_trooper_hands'), ('r_forearm_retopo', 'all_1st_inf_trooper_arms'),
         ('r_forearm_stud', 'all_1st_inf_trooper_arms'))
# the armoured units' own forearms (tools/body_armour.py: forearm_<unit>, its arms texture in the `texture` property),
# drawn by BodyArm in place of the sleeve for the units that name them
# (and the Wookiee's hair skirts, hair_<unit>: BodyArm draws them alpha-tested with the forearm of the same unit)
PARTS = PARTS + tuple((o.name, o['texture']) for o in sorted(bpy.data.objects, key=lambda o: o.name)
                      if o.name.startswith(('forearm_', 'hair_')) and o.type == 'MESH')
# (and another skeleton's parts: meshes on an armature with a `skeleton` property, tools/body_b1.py's b1_hand / b1_arm)
PARTS = PARTS + tuple((o.name, o['texture']) for o in sorted(bpy.data.objects, key=lambda o: o.name)
                      if o.type == 'MESH' and o.parent and o.parent.type == 'ARMATURE' and 'skeleton' in o.parent
                      and 'texture' in o)
rig = bpy.data.objects['r_hand_retopo'].parent
rigs = [rig] + sorted((o for o in bpy.data.objects if o.type == 'ARMATURE' and 'skeleton' in o and o is not rig),
                      key=lambda o: o['skeleton'])
skeleton_names = ['human'] + [o['skeleton'] for o in rigs[1:]]
# bones, parents first, skeleton after skeleton; bidxs[k]: skeleton k's bone names -> index in the one table
order, bone_skeleton, bidxs = [], [], []
def visit(b, k):
    bidxs[k][b.name] = len(order)
    order.append(b)
    bone_skeleton.append(k)
    for c in b.children:
        visit(c, k)
for k, r in enumerate(rigs):
    bidxs.append({})
    for b in r.data.bones:
        if b.parent is None:
            visit(b, k)
bidx = bidxs[0]


def skeleton_of(ob):
    return rigs.index(ob.parent) if ob.parent in rigs else 0
src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'body_poses.py')).read()
ns = {}
exec(src[src.index('FINGERS = '):src.index('scene = bpy.context.scene')], ns)


def f(x):
    return ('%.6g' % x) + ('f' if '.' in '%.6g' % x or 'e' in '%.6g' % x else '.f')


out = ['// generated by tools/body_export.py from re/body/r_arm_weapons.blend: do not edit, never commit',
       '// arm space: metres, wrist at the origin, +y to the middle knuckle, +z the back of the hand (right-handed)']
checks = []
out.append('constexpr BodyArmBone BODY_ARM_BONES[] = {  // name, parent, rest (column vectors, 16), order, roll share')
for b, k in zip(order, bone_skeleton):
    m = b.matrix_local
    cols = [m[r][c] for c in range(4) for r in range(4)]
    eo = 'ZXY' if b.name.endswith('_1') and not b.name.startswith('thumb') else 'XYZ'
    share = {'forearm_twist': 0.5, 'wrist_twist': 1.0}.get(b.name, 0.0)
    out.append('    {"%s", %d, {%s}, "%s", %s},' % (b.name, bidxs[k][b.parent.name] if b.parent else -1,
                                                  ', '.join(f(x) for x in cols), eo, f(share)))
out.append('};')
out.append('#define BODY_ARM_HAS_SKELETONS 1')
out.append('constexpr BodyArmSkeleton BODY_ARM_SKELETONS[] = {  // name, first bone, bone count')
for k, name in enumerate(skeleton_names):
    out.append('    {"%s", %d, %d},' % (name, bone_skeleton.index(k), bone_skeleton.count(k)))
out.append('};')
total_v = total_t = 0
for name, tex in PARTS:
    ob = bpy.data.objects[name]
    pb = bidxs[skeleton_of(ob)]
    me = ob.data
    me.calc_loop_triangles()
    me.calc_normals_split() if hasattr(me, 'calc_normals_split') else None
    uv = me.uv_layers.active.data
    gname = {g.index: g.name for g in ob.vertex_groups}
    key_of, verts, tris = {}, [], []
    for t in me.loop_triangles:
        tri = []
        for li, vi in zip(t.loops, t.vertices):
            u = uv[li].uv
            k = (vi, round(u.x, 5), round(u.y, 5))
            if k not in key_of:
                v = me.vertices[vi]
                ws = sorted(((g.weight, gname[g.group]) for g in v.groups if g.weight > 0 and gname[g.group] in pb),
                            reverse=True)[:4]
                tot = sum(w for w, _ in ws) or 1.0
                ws = [(w / tot, n) for w, n in ws] + [(0.0, 'hand')] * (4 - len(ws))
                n_ = v.normal
                key_of[k] = len(verts)
                verts.append((v.co, n_, (u.x, 1.0 - u.y), ws))
            tri.append(key_of[k])
        tris.append(tri)
    bad = sum(1 for _, _, _, ws in verts if abs(sum(w for w, _ in ws) - 1) > 1e-4)
    checks.append('%s: %d vertices, %d triangles, texture %s, weights not summing to 1: %d' % (
        name, len(verts), len(tris), tex, bad))
    total_v += len(verts)
    total_t += len(tris)
    # (hair_x beside forearm_x, and another skeleton's parts by their whole names)
    cname = ('_'.join(name.split('_')[1:]) if not name.startswith('hair_') and not skeleton_of(ob) else name).upper()
    out.append('constexpr BodyArmVertex %s_VERTICES[] = {  // position, normal, uv (v down), bones, weights' % cname)
    for co, n_, u, ws in verts:
        out.append('    {{%s}, {%s}, {%s}, {%s}, {%s}},' % (
            ', '.join(f(x) for x in co), ', '.join(f(x) for x in n_), ', '.join(f(x) for x in u),
            ', '.join(str(pb[n]) for _, n in ws), ', '.join(f(w) for w, _ in ws)))
    out.append('};')
    out.append('constexpr unsigned short %s_INDICES[] = {' % cname)
    for i in range(0, len(tris), 8):
        out.append('    ' + ' '.join('%d, %d, %d,' % tuple(t) for t in tris[i:i + 8]))
    out.append('};')
out.append('constexpr BodyArmPart BODY_ARM_PARTS[] = {  // name, texture, vertices, count, indices, count')
for name, tex in PARTS:
    cname = ('_'.join(name.split('_')[1:]) if not name.startswith('hair_') and not skeleton_of(bpy.data.objects[name])
             else name).upper()
    k = skeleton_of(bpy.data.objects[name])
    out.append('    {"%s", "%s", %s_VERTICES, sizeof(%s_VERTICES) / sizeof(%s_VERTICES[0]), %s_INDICES, '
               'sizeof(%s_INDICES) / sizeof(%s_INDICES[0])%s},' % ((name, tex) + (cname,) * 6 + (
                   ', %d' % k if k else '',)))
out.append('};')
# poses: one row per bone angle
out.append('constexpr BodyArmPoseAngle BODY_ARM_POSE_ANGLES[] = {  // pose, bone, degrees x y z')
labels = []
for group, ps in ns['GROUPS']:
    k = next((k for k, n in enumerate(skeleton_names) if k and group.startswith(n + ' ')), 0)
    for label, p in ps:
        labels.append('%s: %s' % (group, label))
        for bn, d in p.items():
            if bn in bidxs[k]:
                out.append('    {%d, %d, {%s}},' % (len(labels) - 1, bidxs[k][bn], ', '.join(f(x) for x in d)))
out.append('};')
out.append('constexpr const char* BODY_ARM_POSE_NAMES[] = {')
out += ['    "%s",' % l.replace('"', "'") for l in labels]
out.append('};')
out.append('constexpr BodyArmGrip BODY_ARM_GRIPS[] = {  // weapon, msh model space -> the hand bone rest frame '
           '(column vectors; carries our scale and the msh -> arm axes), '
           'its grip axis in the hand: point, direction (from the frame toward the butt)')
grips = [o for o in bpy.data.objects if o.name.startswith('weap_')]
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mshgeo
import numpy as np
for o in grips:
    # the weapon's own model space (the msh's coordinates, as the game draws it) -> our arm space: fitted over its
    # vertices (tools/body_weapons.py keeps their order), then relative to the hand bone
    # the ammo canister (tools/body_canister.py): the powerup item's msh, every drawn segment
    is_canister = o.name == 'weap_ammocanister'
    k = skeleton_of(o)
    hb = rigs[k].matrix_world @ rigs[k].data.bones['hand'].matrix_local
    short = o.get('grip', o.name[5:])  # (a copy for another skeleton: weap_b1_<grip>, property grip)
    if 'msh' in o:  # a common model (tools/body_weapons.py `com:` / item_ objects)
        weapon_msh = o['msh']
    elif len(short) > 4 and short[3] == '_':  # another side's weapon (tools/body_weapons.py resolve): imp_rifle
        side_dir = {'all': 'ALL', 'wok': 'ALL', 'imp': 'IMP', 'rep': 'REP', 'cis': 'CIS'}[short[:3]]
        weapon_msh = os.path.join(MSH_DIR.replace('/ALL/', '/%s/' % side_dir), '%s_1st_weap_inf_%s.msh' % (short[:3], short[4:]))
    else:
        weapon_msh = os.path.join(MSH_DIR, 'all_1st_weap_inf_%s.msh' % short)
    item_scale = o.get('item_scale', 1.0)  # Holster draws it at this size: the grip is for the msh before it
    if o.get('direct'):  # placed directly (tools/body_sbd.py: the object's local space is the msh's)
        from mathutils import Matrix
        m = hb.inverted() @ o.matrix_world
        sc = sum(m.to_3x3().col[i].length for i in range(3)) / 3
        checks.append('grip %s: placed directly, scale %.4f, det %.3f' % (short, sc, m.to_3x3().determinant()))
        g = json.load(open(os.path.join('re', 'body', 'grip-%s.json' % o.name)))
        point, direction = g['axis_point'], g['axis_direction']
        out.append('    {"%s", {%s}, {%s}, {%s}%s},' % (short, ', '.join(f(m[r][c]) for c in range(4) for r in range(4)),
                                                    ', '.join(f(x) for x in point), ', '.join(f(x) for x in direction),
                                                    ', %d' % k if k else ''))
        continue
    model = mshgeo.load(CANISTER_MSH if is_canister else weapon_msh)
    raw = []
    for node in model['nodes']:
        if not mshgeo.is_drawn(node) or 'lens' in node['name'].lower():
            continue
        for seg in node['segments']:
            if not is_canister and (not seg.get('uv') or not seg.get('texture') or seg['texture'].endswith('.pic')):
                continue
            raw += [tuple(p_) for p_ in seg['wpos']]
    placed = [o.matrix_world @ v.co for v in o.data.vertices]
    assert len(raw) == len(placed), (o.name, len(raw), len(placed))
    X = np.array([[*r, 1.0] for r in raw])
    Y = np.array([list(q) for q in placed])
    A, res, _, _ = np.linalg.lstsq(X, Y, rcond=None)
    err = np.abs(X @ A - Y).max()
    from mathutils import Matrix
    Am = Matrix([list(A[:, r]) for r in range(3)] + [[0, 0, 0, 1]])
    m = hb.inverted() @ Am
    if item_scale != 1.0:  # the game draws weapon * (scale * msh): the matrix takes the scaled msh
        m = m @ Matrix.Scale(1 / item_scale, 4)
    sc = (m.to_3x3().col[0].length + m.to_3x3().col[1].length + m.to_3x3().col[2].length) / 3
    checks.append('grip %s: msh -> hand bone fitted over %d vertices, worst %.3f mm, scale %.4f, det %.3f' % (
        short, len(raw), err * 1000, sc, m.to_3x3().determinant()))
    # the grip's axis in the hand (tools/body_placeweapon.py); the thermal (no handle) round its centre, across the palm
    jp = os.path.join('re', 'body', 'grip-%s.json' % o.name)
    if os.path.exists(jp):
        g = json.load(open(jp))
        point, direction = g['axis_point'], g['axis_direction']
    else:
        c = sum((o.matrix_world @ v.co for v in o.data.vertices), Vector()) / len(o.data.vertices)
        point, direction = list(hb.inverted() @ c), [1.0, 0.0, 0.0]
    checks.append('grip %s axis: point %s mm, direction %s' % (
        short, ' '.join('%.0f' % (x * 1000) for x in point), ' '.join('%.2f' % x for x in direction)))
    out.append('    {"%s", {%s}, {%s}, {%s}%s},' % (short, ', '.join(f(m[r][c]) for c in range(4) for r in range(4)),
                                                ', '.join(f(x) for x in point), ', '.join(f(x) for x in direction),
                                                ', %d' % k if k else ''))
out.append('};')
# textures of ours drawn in place of the game's (tools/body_recolour.py: the sleeve in the body's grey), A8R8G8B8 rows
# from the top; the game texture's name they replace
# (or a unit's hands baked into our glove's layout under a name of their own: tools/body_unithands.py, UNIT_SKINS)
OVERRIDES = (('all_1st_inf_trooper_arms', os.path.join('re', 'body', 'all_1st_inf_trooper_arms_grey.png')),
             ('all_1st_inf_wookie_hands', os.path.join('re', 'body', 'all_1st_inf_wookie_hands.png')),
             # the Wookiee's texture with its alpha (the game's copy has none usable: run539 drew the hair skirts solid)
             ('all_1st_inf_wookie_hair', os.path.join('re', 'body', 'all_1st_inf_wookie_hair.png')),
             # the super battle droid's first-person texture upscaled 4x (Upscayl ultrasharp-4x; tools/body_sbd.py)
             ('cis_1st_sbdroid_hands', os.path.join('re', 'body', 'hd', 'cis_1st_sbdroid_hands-ultrasharp-4x.png')))
entries = []
for k, (name, path) in enumerate(OVERRIDES):
    if not os.path.exists(path):
        continue
    im = bpy.data.images.load(os.path.abspath(path))
    w, h = im.size
    px = im.pixels[:]
    words = []
    for y in range(h - 1, -1, -1):
        for x in range(w):
            i = 4 * (y * w + x)
            r, g, b, a = (max(0, min(255, round(px[i + c] * 255))) for c in range(4))
            words.append('0x%02x%02x%02x%02xu' % (a, r, g, b))
    out.append('constexpr unsigned BODY_ARM_TEXTURE_%d[] = {' % k)
    for i in range(0, len(words), 16):
        out.append('    ' + ', '.join(words[i:i + 16]) + ',')
    out.append('};')
    entries.append('    {"%s", %d, %d, BODY_ARM_TEXTURE_%d},' % (name, w, h, k))
    checks.append('texture %s replaced by %s (%d x %d)' % (name, path, w, h))
out.append('constexpr BodyArmTexture BODY_ARM_TEXTURES[] = {  // ours in place of the game texture of that name')
out += entries or ['    {nullptr, 0, 0, nullptr},']
out.append('};')
os.makedirs(os.path.dirname(os.path.abspath(OUT)), exist_ok=True)
open(OUT, 'w', newline='\n').write('\n'.join(out) + '\n')
print('EXPORT skeletons: %s' % ', '.join('%s %d bones' % (n, bone_skeleton.count(k))
                                         for k, n in enumerate(skeleton_names)))
print('EXPORT %s: %d bones, %d vertices, %d triangles, %d poses, %d grips, %.0f KB' % (
    OUT, len(order), total_v, total_t, len(labels), len(grips),
    os.path.getsize(OUT) / 1024))
for c in checks:
    print('EXPORT  ' + c)
